-- Создание таблицы для контента страниц

-- Создаем таблицу для хранения контента страниц
CREATE TABLE IF NOT EXISTS page_content (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  page_key TEXT NOT NULL UNIQUE,
  title TEXT NOT NULL,
  content_html TEXT NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Создаем индекс для быстрого поиска по ключу страницы
CREATE INDEX IF NOT EXISTS idx_page_content_key ON page_content(page_key);

-- Добавляем комментарии
COMMENT ON TABLE page_content IS 'Контент статических страниц сайта';
COMMENT ON COLUMN page_content.page_key IS 'Уникальный ключ страницы (например: delivery, about, faq)';
COMMENT ON COLUMN page_content.title IS 'Заголовок страницы';
COMMENT ON COLUMN page_content.content_html IS 'HTML контент страницы';

