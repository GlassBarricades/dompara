-- Создание таблицы для часто задаваемых вопросов (FAQ)

-- Создаем таблицу для FAQ
CREATE TABLE IF NOT EXISTS faq_items (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  question TEXT NOT NULL,
  answer TEXT NOT NULL,
  sort_order INTEGER NOT NULL DEFAULT 0,
  is_active BOOLEAN NOT NULL DEFAULT true,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Создаем индекс для сортировки активных FAQ
CREATE INDEX IF NOT EXISTS idx_faq_items_active_sort ON faq_items(is_active, sort_order) WHERE is_active = true;

-- Добавляем комментарии
COMMENT ON TABLE faq_items IS 'Часто задаваемые вопросы для отображения на главной странице';
COMMENT ON COLUMN faq_items.question IS 'Вопрос';
COMMENT ON COLUMN faq_items.answer IS 'Ответ (может содержать HTML)';
COMMENT ON COLUMN faq_items.sort_order IS 'Порядок сортировки (по возрастанию)';
COMMENT ON COLUMN faq_items.is_active IS 'Активен ли вопрос (показывать на главной странице)';

